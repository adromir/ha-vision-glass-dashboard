export function getBuiltinDockIcon(id, size = 19) {
  switch (id) {
    case 'lighting': return renderIcon('light', { size, cls: 'icon-light' });
    case 'climate': return renderIcon('climate', { size, cls: 'icon-climate' });
    case 'stats': return renderIcon('chart-bar', { size, cls: 'icon-stats' });
    case 'security': return renderIcon('lock-closed', { size, cls: 'icon-security' });
    case 'alarmo': return renderIcon('shield', { size, cls: 'icon-alarmo' });
    case 'switches': return renderIcon('plug', { size, cls: 'icon-switch' });
    case 'battery': return renderIcon('battery-full', { size, cls: 'icon-battery' });
    case 'weather': return renderIcon('weather-partlycloudy', { size, cls: 'icon-weather' });
    case 'settings': return renderIcon('settings', { size });
    default: return renderIcon('star', { size });
  }
}

export function resolveEntityIcon(entityId, stateObj) {
    if (!entityId) return renderIcon('activity', { size: 16 });

    const attrs = (stateObj && stateObj.attributes) || {};
    const devClass = (attrs.device_class || '').toLowerCase();
    const unit = (attrs.unit_of_measurement || '').toLowerCase();
    const eId = entityId.toLowerCase();
    const fn = (attrs.friendly_name || '').toLowerCase();
    const val = stateObj ? String(stateObj.state).toLowerCase() : '';

    // 1. Device classes
    if (devClass === 'temperature') return renderIcon('thermometer', { size: 16, cls: 'icon-temp' });
    if (devClass === 'humidity') return renderIcon('droplet', { size: 16, cls: 'icon-humidity' });
    if (devClass === 'illuminance') return renderIcon('lux', { size: 16, cls: 'icon-lux' });
    if (devClass === 'battery') {
      const num = parseFloat(val);
      if (!isNaN(num) && num < 20) return renderIcon('battery-critical', { size: 16, color: '#ef4444' });
      if (!isNaN(num) && num <= 40) return renderIcon('battery-low', { size: 16, color: '#f59e0b' });
      return renderIcon('battery-full', { size: 16, cls: 'icon-battery' });
    }
    if (devClass === 'motion' || devClass === 'occupancy' || devClass === 'presence') {
      return renderIcon(val === 'on' ? 'motion' : 'motion-idle', { size: 16, cls: 'icon-security' });
    }
    if (devClass === 'window') return renderIcon(val === 'on' ? 'window-open' : 'window', { size: 16, cls: 'icon-climate' });
    if (devClass === 'door' || devClass === 'garage_door') return renderIcon(val === 'on' ? 'door-open' : 'door', { size: 16, cls: 'icon-security' });
    if (devClass === 'lock') return renderIcon(val === 'locked' ? 'lock-closed' : 'lock-open', { size: 16, cls: 'icon-security' });
    if (devClass === 'power' || devClass === 'energy' || devClass === 'current' || devClass === 'voltage') {
      return renderIcon('zap', { size: 16, color: '#f59e0b' });
    }
    if (devClass === 'signal_strength') return renderIcon('wifi', { size: 16, cls: 'icon-stats' });
    if (devClass === 'restart') return renderIcon('restart', { size: 16, cls: 'icon-switch' });

    // 2. Units of measurement
    if (unit.includes('°c') || unit.includes('°f') || unit === 'k') {
      return renderIcon('thermometer', { size: 16, cls: 'icon-temp' });
    }
    if (unit === 'lx' || unit === 'lux') {
      return renderIcon('lux', { size: 16, cls: 'icon-lux' });
    }
    if (unit === '%') {
      if (eId.includes('batt') || fn.includes('batt')) {
        const num = parseFloat(val);
        if (!isNaN(num) && num < 20) return renderIcon('battery-critical', { size: 16, color: '#ef4444' });
        if (!isNaN(num) && num <= 40) return renderIcon('battery-low', { size: 16, color: '#f59e0b' });
        return renderIcon('battery-full', { size: 16, cls: 'icon-battery' });
      }
      if (eId.includes('feucht') || eId.includes('hum') || fn.includes('feucht') || fn.includes('hum')) {
        return renderIcon('droplet', { size: 16, cls: 'icon-humidity' });
      }
      return renderIcon('percent', { size: 16, cls: 'icon-stats' });
    }
    if (unit === 'w' || unit === 'kw' || unit === 'kwh' || unit === 'v' || unit === 'a') {
      return renderIcon('zap', { size: 16, color: '#f59e0b' });
    }
    if (unit === 'km/h' || unit === 'm/s') {
      return renderIcon('wind', { size: 16, cls: 'icon-weather' });
    }
    if (unit === 'db' || unit === 'dbm') {
      return renderIcon('wifi', { size: 16, cls: 'icon-stats' });
    }
    if (unit === 's' || unit === 'min' || unit === 'h' || unit === 'd') {
      return renderIcon('clock', { size: 16, cls: 'icon-calendar' });
    }

    // 3. Name & Entity ID keywords
    const text = `${eId} ${fn}`;
    if (text.includes('wecker') || text.includes('alarm')) {
      return renderIcon('alarm', { size: 16, color: '#f59e0b' });
    }
    if (text.includes('indikator') || text.includes('indicator') || text.includes('led')) {
      return renderIcon('eye', { size: 16, cls: 'icon-light' });
    }
    if (text.includes('restart') || text.includes('neustart') || text.includes('reboot')) {
      return renderIcon('restart', { size: 16, cls: 'icon-switch' });
    }
    if (text.includes('tastensperre') || text.includes('childlock') || text.includes('kindersicherung') || text.includes('sperre')) {
      return renderIcon('lock-closed', { size: 16, cls: 'icon-security' });
    }
    if (text.includes('urlaub') || text.includes('holiday') || text.includes('vacation')) {
      return renderIcon('plane', { size: 16, cls: 'icon-stats' });
    }
    if (text.includes('sommer') || text.includes('summer')) {
      return renderIcon('sun', { size: 16, cls: 'icon-sun' });
    }
    if (text.includes('winter') || text.includes('frost')) {
      return renderIcon('weather-snowy', { size: 16, cls: 'icon-weather' });
    }
    if (text.includes('fenster') || text.includes('window')) {
      return renderIcon(val === 'on' ? 'window-open' : 'window', { size: 16, cls: 'icon-climate' });
    }
    if (text.includes('tür') || text.includes('door') || text.includes('tor')) {
      return renderIcon(val === 'on' ? 'door-open' : 'door', { size: 16, cls: 'icon-security' });
    }
    if (text.includes('beweg') || text.includes('motion') || text.includes('präsenz') || text.includes('presence')) {
      return renderIcon(val === 'on' ? 'motion' : 'motion-idle', { size: 16, cls: 'icon-security' });
    }
    if (text.includes('komfort') || text.includes('comfort') || text.includes('heizen') || text.includes('heat')) {
      return renderIcon('flame', { size: 16, cls: 'icon-climate' });
    }
    if (text.includes('eco') || text.includes('spar') || text.includes('leaf')) {
      return renderIcon('leaf', { size: 16, cls: 'icon-battery' });
    }
    if (text.includes('temperatur') || text.includes('temp') || text.includes('wärme')) {
      return renderIcon('thermometer', { size: 16, cls: 'icon-temp' });
    }
    if (text.includes('feucht') || text.includes('humidity')) {
      return renderIcon('droplet', { size: 16, cls: 'icon-humidity' });
    }
    if (text.includes('hellig') || text.includes('lux') || text.includes('illuminance')) {
      return renderIcon('lux', { size: 16, cls: 'icon-lux' });
    }
    if (text.includes('batterie') || text.includes('battery')) {
      return renderIcon('battery-medium', { size: 16, cls: 'icon-battery' });
    }
    if (text.includes('waschmaschine') || text.includes('washing')) {
      return renderIcon('washing-machine', { size: 16, cls: 'icon-switch' });
    }
    if (text.includes('multimedia') || text.includes('tv') || text.includes('fernseh') || text.includes('shield')) {
      return renderIcon('tv', { size: 16, cls: 'icon-media' });
    }
    if (text.includes('receiver') || text.includes('denon') || text.includes('subwoofer') || text.includes('audio') || text.includes('sound') || text.includes('lautsprecher')) {
      return renderIcon('speaker', { size: 16, cls: 'icon-media' });
    }
    if (text.includes('plan') || text.includes('zeit') || text.includes('time') || text.includes('dauer') || text.includes('nächste')) {
      return renderIcon('clock', { size: 16, cls: 'icon-calendar' });
    }
    if (text.includes('sensitiv') || text.includes('empfind') || text.includes('distanz') || text.includes('bereich') || text.includes('modus') || text.includes('mode')) {
      return renderIcon('sliders', { size: 16, cls: 'icon-stats' });
    }

    // 4. Domain & Helper Fallbacks
    if (eId.startsWith('light.')) return renderIcon('light', { size: 16, cls: 'icon-light' });
    if (eId.startsWith('switch.')) return renderIcon('power', { size: 16, cls: 'icon-switch' });
    if (eId.startsWith('input_boolean.')) return renderIcon('toggle-right', { size: 16, cls: 'icon-switch' });
    if (eId.startsWith('input_number.')) return renderIcon('sliders', { size: 16, cls: 'icon-stats' });
    if (eId.startsWith('input_datetime.')) return renderIcon('clock', { size: 16, cls: 'icon-calendar' });
    if (eId.startsWith('input_select.')) return renderIcon('list', { size: 16, cls: 'icon-stats' });
    if (eId.startsWith('input_text.')) return renderIcon('type', { size: 16, cls: 'icon-stats' });
    if (eId.startsWith('input_button.') || eId.startsWith('button.')) return renderIcon('play', { size: 16, cls: 'icon-switch' });
    if (eId.startsWith('automation.')) return renderIcon('cpu', { size: 16, cls: 'icon-switch' });
    if (eId.startsWith('script.')) return renderIcon('code', { size: 16, cls: 'icon-switch' });
    if (eId.startsWith('scene.')) return renderIcon('sparkles', { size: 16, cls: 'icon-light' });
    if (eId.startsWith('timer.')) return renderIcon('timer', { size: 16, cls: 'icon-stats' });
    if (eId.startsWith('climate.')) return renderIcon('climate', { size: 16, cls: 'icon-climate' });
    if (eId.startsWith('media_player.')) return renderIcon('music', { size: 16, cls: 'icon-media' });
    if (eId.startsWith('alarm_control_panel.')) return renderIcon('shield', { size: 16, cls: 'icon-alarmo' });
    if (eId.startsWith('cover.')) return renderIcon('blinds', { size: 16, cls: 'icon-climate' });
    if (eId.startsWith('fan.')) return renderIcon('fan', { size: 16, cls: 'icon-climate' });
    if (eId.startsWith('vacuum.')) return renderIcon('vacuum', { size: 16, cls: 'icon-switch' });
    if (eId.startsWith('camera.')) return renderIcon('camera', { size: 16, cls: 'icon-security' });
    if (eId.startsWith('lock.')) return renderIcon(val === 'locked' ? 'lock-closed' : 'lock-open', { size: 16, cls: 'icon-security' });
    if (eId.startsWith('person.')) return renderIcon('user-walk', { size: 16, cls: 'icon-security' });
    if (eId.startsWith('zone.')) return renderIcon('map-pin', { size: 16, cls: 'icon-stats' });
    if (eId.startsWith('update.')) return renderIcon('arrow-up-circle', { size: 16, cls: 'icon-stats' });
    if (eId.startsWith('siren.')) return renderIcon('bell', { size: 16, cls: 'icon-security' });
    if (eId.startsWith('weather.')) return renderIcon('weather-partlycloudy', { size: 16, cls: 'icon-weather' });
    if (eId.startsWith('binary_sensor.')) return renderIcon(val === 'on' ? 'check' : 'activity', { size: 16, cls: 'icon-security' });
    if (eId.startsWith('sensor.')) return renderIcon('activity', { size: 16, cls: 'icon-stats' });

    return renderIcon('activity', { size: 16 });
}
